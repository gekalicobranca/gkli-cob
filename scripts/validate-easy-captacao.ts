const preview:ConversaoPreview={tipoConversao:'cobrancas',origem:'Teste',arquivo:'relatorio.xlsx',totalParcelas:1,valorTotal:100.01,padraoDetectado:null,cobrancas:[{unidade:'001',valorTotal:100.01,vencimento:'10/09/2026',vencimentoMaisAntigo:'10/09/2026',responsavel:'Teste',parcelas:[]}],unidades:[],inconsistencias:[],csv:'',xlsxBase64:''};
test('prévia valida valores e exige leitura completa antes da substituição',()=>{
  assert.deepEqual(validarPreviaCaptacao(preview),{cobrancas:1,unidades:1,valor:100.01});
  for(const p of [ {...preview,cobrancas:[]}, {...preview,valorTotal:10}, {...preview,cobrancas:[preview.cobrancas[0],preview.cobrancas[0]]}, {...preview,inconsistencias:['Linha ignorada: valor inválido.']}, {...preview,cobrancas:[{...preview.cobrancas[0],vencimento:'30/02/2026'}]}, {...preview,cobrancas:[{...preview.cobrancas[0],juros:-1}]} ]) assert.throws(()=>validarPreviaCaptacao(p));
});
test('assinatura vincula arquivo, operador, conversão, condomínio e carteira',()=>{
  const p={...preview,easyCaptacao:{operadorId:'operador',assinatura:''}};
  p.easyCaptacao.assinatura=gerarAssinaturaCaptacao('chave-de-teste','id','condo','carteira',p);
  const reordered=JSON.parse(JSON.stringify(p,Object.keys(p).sort()));
  assert.doesNotThrow(()=>verificarAssinaturaCaptacao('chave-de-teste','id','condo','carteira',p,'operador'));
  assert.throws(()=>verificarAssinaturaCaptacao('chave-de-teste','id','outro','carteira',p,'operador'));
  assert.throws(()=>verificarAssinaturaCaptacao('chave-de-teste','outro','condo','carteira',p,'operador'));
  assert.throws(()=>verificarAssinaturaCaptacao('chave-de-teste','id','condo','carteira',p,'outro'));
  assert.throws(()=>verificarAssinaturaCaptacao('chave-de-teste','id','condo','carteira',{...p,valorTotal:1},'operador'));
  assert.equal(typeof reordered,'object');
  const reverse=Object.fromEntries(Object.entries(p).reverse());
  assert.doesNotThrow(()=>verificarAssinaturaCaptacao('chave-de-teste','id','condo','carteira',reverse,'operador'));
});
