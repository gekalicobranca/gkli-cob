test('PostgreSQL usa limpeza real do Maestro, bloqueia prévia obsoleta e preserva acordos e demais status',async()=>{
  const db=new PGlite();
  const condo=randomUUID(),wallet=randomUUID(),conv=randomUUID(),other=randomUUID();
  const ids=Array.from({length:8},()=>randomUUID());
  const year=new Date().getUTCFullYear();
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create table condominios(id uuid primary key,carteira_id uuid);
    create table unidades(id uuid primary key,bloco text);
    create table conversoes_relatorio(id uuid primary key,origem text,status text,preview_json jsonb,carteira_id uuid,condominio_id uuid,limpeza_maestro_em timestamptz,atualizado_em timestamptz);
    create table cobrancas(id uuid primary key,carteira_id uuid,condominio_id uuid,unidade_id uuid,status_operacional text,vencimento date,valor_atualizado numeric,duplicada_de_id uuid);
    create table acordos(id uuid primary key,cobranca_id uuid references cobrancas);
    create table acordo_cobrancas(cobranca_id uuid references cobrancas);
    create table agente_administradoras(id uuid primary key,ativo boolean);
    create table agente_receitas(id uuid primary key,administradora_id uuid,ativo boolean,script_key text,config_json jsonb);
    create table mensagens(id uuid,cobranca_id uuid,cobranca_flow_id uuid,payload jsonb,status text,status_operacional text,cancelado_em timestamptz,cancelada_em timestamptz,agendada_para timestamptz,scheduled_at timestamptz,motivo_cancelamento text);
    create table lote_itens(cobranca_id uuid,cobranca_flow_id uuid);
    create table cobranca_flows(id uuid,payload jsonb,total_mensagens integer,total_pendentes integer,total_agendadas integer,total_enviadas integer,total_falhas integer,proximo_disparo_em timestamptz,status text,cancelado_em timestamptz);
    create table flow_progressao(cobranca_ids uuid[],status text,token text,lease_ate timestamptz,erro text,updated_at timestamptz);
    create table maestro_flow_montagens(plano jsonb,status text,token text,lease_ate timestamptz,updated_at timestamptz);
    create table central_pendencias(cobranca_id uuid,entidade_tipo text,entidade_id uuid,status text,resolvido_em timestamptz,payload jsonb);
    create table auditoria_eventos(carteira_id uuid,entidade_tipo text,entidade_id uuid,evento_tipo text,titulo text,descricao text,antes jsonb,depois jsonb);
    insert into condominios values('${condo}','${wallet}');
    insert into conversoes_relatorio values('${conv}','easy_captacao','preview','{"easyCaptacao":{"substituicao":{"ano":${year}}}}','${wallet}','${condo}',null,null);
  `);
  const rows=[['regular',year,condo],['novo',year,condo],['em_cobranca_ativa',year,condo],['em_negociacao',year,condo],['suspenso',year,condo],['novo',year-1,condo],['novo',year,other],['novo',year,condo]];
  for(const [index,[status,ano,cond]] of rows.entries()) await db.query('insert into cobrancas values($1,$2,$3,$4,$5,$6,100,null)',[ids[index],wallet,cond,randomUUID(),status,`${ano}-03-01`]);
  await db.query('insert into acordos values($1,$2)',[randomUUID(),ids[7]]);
  await db.exec(await readFile('supabase/migrations/20261016182723_living_subcondominio_escopo.sql','utf8'));
  await db.exec(await readFile('supabase/migrations/20261108131331_easy_captacao_maestro.sql','utf8'));
  const snap=async()=> (await db.query<{r:{quantidade:number;versao:string}}>('select easy_captacao_snapshot($1,$2) r',[condo,wallet])).rows[0].r;
  const before=await snap();assert.equal(before.quantidade,3);
  await db.query('update cobrancas set valor_atualizado=101 where id=$1',[ids[0]]);
  await assert.rejects(()=>db.query('select easy_preparar_captacao($1,$2)',[conv,before.versao]),/mudaram/);
  assert.equal((await db.query<{n:number}>('select count(*) as n from cobrancas')).rows[0].n,8);
  const current=await snap();
  const result=await db.query<{r:{removidas:number}}>('select easy_preparar_captacao($1,$2) r',[conv,current.versao]);
  assert.equal(result.rows[0].r.removidas,3);
  assert.deepEqual((await db.query<{id:string}>('select id from cobrancas')).rows.map(r=>r.id).sort(),ids.slice(3).sort());
  assert.equal((await db.query<{n:number}>('select count(*) as n from auditoria_eventos')).rows[0].n,1);
  await assert.rejects(()=>db.query('select easy_preparar_captacao($1,$2)',[conv,current.versao]),/já foi confirmada/);
  await db.exec('set role authenticated');
  await assert.rejects(()=>db.query('select easy_captacao_snapshot($1,$2)',[condo,wallet]),/permission denied/);
  await db.exec('reset role');
  await db.close();
});
